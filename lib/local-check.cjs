'use strict';
// 安装包自检：只操作隔离的本地数据，不访问抖音或模型接口。
const fs = require('node:fs');
const path = require('node:path');
module.exports = async function check(win, app, service, secrets) {
  const dir = path.resolve(app.commandLine.getSwitchValue('verification-dir') || path.join(app.getPath('userData'), 'verification'));
  fs.mkdirSync(dir, { recursive: true });
  const errors = [], report = { binary: process.execPath, packaged: app.isPackaged, versions: { electron:process.versions.electron,node:process.versions.node }, pages:[], interactions:[] };
  const evaluate = code => win.webContents.executeJavaScript(code);
  const until = async predicate => { for(let i=0;i<70;i++){if(await predicate())return;await new Promise(r=>setTimeout(r,100))}throw new Error('交互检查超时'); };
  win.webContents.setBackgroundThrottling(false);
  win.webContents.on('console-message', (_event, level, message) => { if(level>=3)errors.push(message); });
  await new Promise(r=>setTimeout(r,1200));
  for (const page of ['dashboard','tasks','leads','review','logs','settings']) {
    await win.webContents.executeJavaScript(`location.hash=${JSON.stringify(page)}`);
    await new Promise(r=>setTimeout(r,1000));
    const result=await win.webContents.executeJavaScript(`({title:document.querySelector('h1')?.textContent,overflow:document.documentElement.scrollWidth>innerWidth,node:typeof require,errors:document.body.textContent.includes('加载失败')})`);
    if(!result.title || result.overflow || result.node!=='undefined' || result.errors)throw new Error('界面自检失败：'+page);
    report.pages.push({page,...result});
    fs.writeFileSync(path.join(dir,page+'.png'),(await win.webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG());
  }
  const before=service.state();
  if(before.bridge.connected || before.tasks.length || before.drafts.length || before.settings.keyConfigured)throw new Error('隔离数据检查失败');
  await evaluate("document.querySelector('[name=replyTemplate]').value='界面保存自检模板';document.querySelector('#settingsForm').requestSubmit()");
  await until(()=>service.settings().replyTemplate==='界面保存自检模板');
  report.interactions.push('通过真实设置表单保存模板');
  await until(()=>evaluate("!document.querySelector('[data-action=toggleMcp]').disabled"));
  await evaluate("document.querySelector('[data-action=toggleMcp]').click()");
  await until(()=>service.store.meta('mcpEnabled')===true);
  const rpc = async (method,params,id) => {
    const r=await fetch('http://127.0.0.1:19423/mcp',{method:'POST',headers:{'Content-Type':'application/json',Accept:'application/json, text/event-stream','MCP-Protocol-Version':'2025-11-25',Authorization:'Bearer '+secrets.get('mcpToken')},body:JSON.stringify({jsonrpc:'2.0',id,method,params})});
    if(!r.ok)throw new Error('安装包 MCP 请求失败 HTTP '+r.status);return r.json();
  };
  const init=await rpc('initialize',{protocolVersion:'2025-11-25',capabilities:{},clientInfo:{name:'packaged-self-check',version:'1.0.0'}},1);
  if(!init.result?.serverInfo)throw new Error('MCP 初始化失败');
  const tools=await rpc('tools/list',{},2);
  if(tools.result?.tools?.length!==10)throw new Error('MCP 工具发现失败');
  const status=await rpc('tools/call',{name:'get_status',arguments:{}},3);
  if(status.error||status.result?.isError)throw new Error('MCP 状态查询失败');
  report.interactions.push('通过界面开启 MCP，安装包实际 HTTP 初始化、10 个工具发现及状态查询');
  await evaluate("document.querySelector('#mcpPanel').scrollIntoView()");
  await new Promise(r=>setTimeout(r,300));
  fs.writeFileSync(path.join(dir,'mcp.png'),(await win.webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG());
  await until(()=>evaluate("!document.querySelector('[data-action=toggleMcp]').disabled"));
  await evaluate("document.querySelector('[data-action=toggleMcp]').click()");
  await until(()=>service.store.meta('mcpEnabled')===false);
  const disabled=await fetch('http://127.0.0.1:19423/mcp',{method:'POST',headers:{Authorization:'Bearer '+secrets.get('mcpToken')}});
  if(disabled.status!==503)throw new Error('MCP 关闭未生效');
  report.interactions.push('通过界面关闭 MCP 后拒绝请求');
  // 只在隔离的自检数据库中注入明确测试数据，验证用户点击及取消编辑不会改变草稿。
  const {taskConfig,matchComment}=require('./rules.cjs');
  const config=taskConfig({search:'测试',include:'报价',exclude:''});
  const taskId=service.store.createTask(config,'1234567890'), task=service.store.task(taskId);
  const comment={id:'1111111111111111111',user_id:'22222222222',nickname:'本地测试',body:'报价 <img src=x onerror=alert(1)>',created:1};
  service.store.addComment(task,{id:'3333333333333333333',title:'隔离测试视频'},comment,'测试',matchComment(comment.body,config));
  const draftId=service.store.addDraft(service.store.source(comment.id,taskId),taskId,'reply','原始自检草稿');
  await evaluate("location.hash='review';window.scrollTo(0,0)");
  await until(()=>evaluate("!!document.querySelector('[data-action=editDraft]')"));
  if(await evaluate("!!document.querySelector('.draft-grid img')"))throw new Error('外部评论 HTML 未转义');
  await evaluate("document.querySelector('[data-action=editDraft]').click()");
  await until(()=>evaluate("document.querySelector('#editor').open"));
  await evaluate("document.querySelector('#editorText').value='已保存的自检草稿';document.querySelector('#editorForm [value=save]').click()");
  await until(()=>service.store.draft(draftId).version===2);
  await until(()=>evaluate("!document.querySelector('[data-action=editDraft]').disabled"));
  await evaluate("document.querySelector('[data-action=editDraft]').click()");
  await until(()=>evaluate("document.querySelector('#editor').open"));
  await evaluate("document.querySelector('#editorText').value='取消时不得保存';document.querySelector('#editor').close()");
  await new Promise(r=>setTimeout(r,500));
  if(service.store.draft(draftId).version!==2||service.store.draft(draftId).content!=='已保存的自检草稿')throw new Error('取消编辑错误地保存了文案');
  report.interactions.push('草稿实际编辑保存、再次编辑取消保持原内容及版本、外部 HTML 作为文本显示');
  report.passed = errors.length===0;report.errors=errors;
  fs.writeFileSync(path.join(dir,'report.json'),JSON.stringify(report,null,2));
  if(errors.length)throw new Error('界面出现控制台错误');
};
